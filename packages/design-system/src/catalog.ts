import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

import { localFile, object, readJson, unique } from './files.ts';
import type { Pattern } from './schema.ts';
import { parsePattern } from './schema.ts';
import { loadTokens } from './tokens.ts';

export type PatternRecord = { contract: Pattern; contractPath: string; guidePath: string; guide: string };
export function loadPatterns(root: string): PatternRecord[] {
  const { profile, tokens } = loadTokens(root);
  const patternRoot = 'packages/design-system/patterns';
  const records = readdirSync(path.join(root, patternRoot), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
      const contractPath = `${patternRoot}/${entry.name}/contract.json`;
      const guidePath = `${patternRoot}/${entry.name}/guide.md`;
      const contract = parsePattern(readJson(localFile(root, contractPath)));
      if (contract.id !== entry.name) throw new Error(`Pattern directory must match id: ${contract.id}`);
      for (const [name, items] of Object.entries({
        roles: contract.roles,
        states: contract.states,
        rules: contract.rules,
        tokenRoles: contract.tokenRoles
      }))
        unique(
          items.map((item) => item.id),
          name
        );
      unique(
        contract.implementations.map((implementation) => implementation.platform),
        'platform implementations'
      );
      for (const role of contract.tokenRoles) {
        if (!profile.roles.some((candidate) => candidate.id === role.id))
          throw new Error(`Unknown token role ${role.id}`);
        for (const platform of role.platforms)
          if (!tokens.get(platform)?.has(role.id)) throw new Error(`Unknown variant ${role.id}/${platform}`);
      }
      for (const implementation of contract.implementations) {
        for (const ref of [...implementation.sourcePaths, ...implementation.testPaths]) localFile(root, ref);
        for (const id of implementation.ruleIds)
          if (!contract.rules.some((rule) => rule.id === id && rule.platforms.includes(implementation.platform)))
            throw new Error(`Unknown/inapplicable rule ${id}`);
        for (const id of implementation.stateIds)
          if (!contract.states.some((state) => state.id === id)) throw new Error(`Unknown state ${id}`);
      }
      for (const ref of contract.designReferences) {
        if (ref.path !== 'design/design-system.pen')
          throw new Error('Design references must target the dedicated design-system.pen');
        const document = readJson(localFile(root, ref.path));
        const ids: string[] = [];
        function visit(value: unknown) {
          if (Array.isArray(value)) for (const child of value) visit(child);
          else if (value && typeof value === 'object') {
            const node = object(value);
            if (typeof node.id === 'string') ids.push(node.id);
            for (const child of Object.values(node)) visit(child);
          }
        }
        visit(document);
        for (const id of ref.nodeIds) if (!ids.includes(id)) throw new Error(`Missing Pencil node ${id}`);
        for (const asset of ref.assetPaths) localFile(root, asset);
      }
      const guide = readFileSync(localFile(root, guidePath), 'utf8');
      if (!guide.startsWith(`# ${contract.title}\n`)) throw new Error(`Guide title must match ${contract.id}`);
      return { contract, contractPath, guidePath, guide };
    })
    .sort((a, b) => a.contract.id.localeCompare(b.contract.id, 'en'));
  if (!records.length) throw new Error('No patterns found');
  unique(
    records.map((record) => record.contract.id),
    'patterns'
  );
  return records;
}
export function catalogFiles(records: PatternRecord[]): Record<string, string> {
  const patterns = records.map(({ contract: c, contractPath, guidePath }) => ({
    id: c.id,
    title: c.title,
    summary: c.summary,
    tags: [...c.tags].sort(),
    status: c.status,
    version: c.version,
    contractPath,
    guidePath,
    tokenRoles: c.tokenRoles,
    platforms: c.implementations.map((i) => ({
      platform: i.platform,
      framework: i.framework,
      stateIds: i.stateIds,
      ruleIds: i.ruleIds,
      exclusions: i.exclusions,
      gaps: i.gaps,
      sourcePaths: i.sourcePaths,
      testPaths: i.testPaths
    })),
    designReferences: c.designReferences
  }));
  return {
    'catalog.json': `${JSON.stringify({ schemaVersion: 1, patterns }, null, 2)}\n`,
    'catalog.md': `# Doma pattern catalog\n\nGenerated by @repo/design-system generate. Paths below are relative to the repository root. Read both contract and guide; references do not imply passing checks.\n\n${records
      .map(
        ({ contract: c, contractPath, guidePath }) =>
          `## ${c.title}\n\n${c.id} · ${c.status} · ${c.version} · ${[...c.tags].sort().join(', ')}\n\n${c.summary}\n\n- [Contract](../../../${contractPath})\n- [Guidance](../../../${guidePath})\n- Platforms: ${c.implementations.map((i) => i.platform).join(', ')}\n- Token roles: ${c.tokenRoles.map((r) => r.id).join(', ')}\n- Native references: ${c.implementations
            .flatMap((i) => [...i.sourcePaths, ...i.testPaths])
            .map((p) => `[${path.basename(p)}](../../../${p})`)
            .join(', ')}\n`
      )
      .join('\n')}`
  };
}
