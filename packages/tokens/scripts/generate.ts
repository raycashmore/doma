import path from 'node:path';

import StyleDictionary from 'style-dictionary';

import { object } from './files.ts';
import { loadTokens, outputName } from './validate.ts';

function color(value: unknown) {
  const literal = object(value);
  const components = literal.components as number[];
  const byte = (number: number) =>
    Math.round(number * 255)
      .toString(16)
      .padStart(2, '0');
  const rgb = components.map(byte).join('');
  const alpha = byte(literal.alpha as number);
  return {
    css: `#${rgb}${alpha === 'ff' ? '' : alpha}`,
    argb: `0x${alpha}${rgb}`.toUpperCase().replace('0X', '0x'),
    swift: `0x${rgb.toUpperCase()}`,
    alpha: literal.alpha as number
  };
}

function dictionary(root: string, sources: string[]) {
  return new StyleDictionary({
    usesDtcg: true,
    source: sources.map((source) => path.join(root, 'packages/tokens', source)),
    log: { verbosity: 'silent', warnings: 'error', errors: { brokenReferences: 'throw' } },
    platforms: { native: { transforms: [] } }
  });
}

// One light and dark pair per colour. `nonisolated` because the app's default isolation is the main
// actor, and SwiftUI resolves dynamic colours off it.
async function swiftTokens(root: string, profile: ReturnType<typeof loadTokens>['profile']): Promise<string> {
  const { allTokens } = await dictionary(root, profile.ios.sources).getPlatformTokens('native');
  const declarations = profile.ios.colors
    .map((id) => ({ id, name: id.split('.').at(-1)! }))
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(({ id, name }) => {
      const [light, dark] = (['light', 'dark'] as const).map((appearance) => {
        const token = allTokens.find((token) => token.path.join('.') === `${id}.${appearance}`);
        if (!token) throw new Error(`Unresolved iOS colour ${id}.${appearance}`);
        return color(token.$value as unknown);
      }) as [ReturnType<typeof color>, ReturnType<typeof color>];
      return `    static let ${name} = DomaColorPair(light: ${light.swift}, lightAlpha: ${light.alpha}, dark: ${dark.swift}, darkAlpha: ${dark.alpha})`;
    });
  return `// Generated by @repo/tokens generate. Colours are sRGB: 0xRRGGBB plus alpha for each appearance.

nonisolated struct DomaColorPair: Sendable {
    let light: UInt32
    let lightAlpha: Double
    let dark: UInt32
    let darkAlpha: Double
}

nonisolated enum DomaTokens {
${declarations.join('\n')}
}
`;
}

// Style Dictionary resolves whole-token aliases before the bounded native adapters run.
export async function tokenFiles(root: string): Promise<Record<string, string>> {
  const { profile } = loadTokens(root);
  const files: Record<string, string> = {};
  const variables: Record<
    string,
    { type: 'color' | 'number'; value: string | number; token: string; platform: string }
  > = {};
  for (const platform of ['web', 'android'] as const) {
    const resolved = await dictionary(root, profile.platforms[platform].sources).getPlatformTokens('native');
    const declarations: string[] = [];
    for (const role of [...profile.roles].sort((a, b) => a.id.localeCompare(b.id))) {
      const token = resolved.allTokens.find((token) => token.path.join('.') === role.id);
      if (!token) throw new Error(`Unresolved role ${role.id}`);
      const name = outputName(role.id);
      const kotlinName = name.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase());
      if (role.type === 'color') {
        const value = color(token.$value as unknown);
        declarations.push(
          platform === 'web' ? `  --doma-${name}: ${value.css};` : `    const val ${kotlinName}: Long = ${value.argb}`
        );
        variables[role.pencilNames[platform]] = { type: 'color', value: value.css, token: role.id, platform };
      } else {
        const value = object(token.$value as unknown).value as number;
        // Android's logical px-to-dp policy is explicit in profile.json; no typography conversion.
        const float = Math.fround(value);
        if (platform === 'android' && (!Number.isFinite(float) || (value !== 0 && float === 0)))
          throw new Error(`Unsupported Android float ${role.id}`);
        declarations.push(
          platform === 'web'
            ? `  --doma-${name}: ${value}px;`
            : `    const val ${kotlinName}: Float = ${/[.e]/i.test(String(value)) ? value : `${value}.0`}f`
        );
        variables[role.pencilNames[platform]] = { type: 'number', value, token: role.id, platform };
      }
    }
    if (platform === 'web')
      files['web/tokens.css'] = `/* Generated by @repo/tokens generate. */\n:root {\n${declarations.join('\n')}\n}\n`;
    else
      files['android/DomaTokens.kt'] =
        `// Generated by @repo/tokens generate. Layout scalars use logical dp.\npackage com.doma.tokens\n\nobject DomaTokens {\n${declarations.join('\n')}\n}\n`;
  }
  files['ios/DomaTokens.swift'] = await swiftTokens(root, profile);
  files['pencil/variables.json'] =
    `${JSON.stringify({ schemaVersion: 1, target: 'design/design-system.pen', variables }, null, 2)}\n`;
  return files;
}
